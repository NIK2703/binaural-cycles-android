#!/bin/bash
# Отправка команды debug-приёмнику и печать ответа.
#
# Использование:  bash tools/dbgcmd.sh status
#                 bash tools/dbgcmd.sh switch 20 250
#
# `am broadcast` печатает resultData построчно, поэтому многострочный ответ
# (status, presets, help) читается прямо из вызова. Если приёмник молчит —
# смотрите logcat: adb logcat -d -t 40 -s BinauralDebug:I '*:S'
#
# Требование: процесс приложения жив. Экран может быть выключен, активити
# уничтожена — исполнитель подключён в Application, поэтому команды работают
# в фоне и НИКОГО НЕ БУДЯТ. Разбудить устройство (если очень нужно):
# input keyevent 224 (экран) и 82 (lockscreen).
#
# ВАЖНО ПРО КАВЫЧКИ: аргументы adb передаются РАЗДЕЛЬНО, adb сам склеивает их
# пробелом, и только шелл устройства снимает одинарные кавычки. Нельзя оборачивать
# весь вызов в одни внешние кавычки с экранированными внутренними — тогда вторая
# пара доедет до приёмника литералом и команда не распознается
# (`Неизвестная команда: "'state'"`).
set -u
ADB=/home/nikita/tools/android-sdk/platform-tools/adb
PKG=com.binauralcycles.debug
ACTION=com.binauralcycles.debug.COMMAND
CMD="$*"

# Внутренние кавычки обязательны: `adb shell` склеивает аргументы через пробел,
# и команда из нескольких слов на устройстве развалилась бы на части.
#
# --include-stopped-packages нужен, чтобы поднять процесс ПОСЛЕ установки,
# когда приложение ещё в «остановленном» состоянии: система по умолчанию
# исключает такие пакеты из broadcast'ов. Активити при этом НЕ запускается —
# отрабатывает только Application.onCreate, который и регистрирует приёмник.
"$ADB" shell am broadcast -a "$ACTION" -p "$PKG" --include-stopped-packages \
    --es cmd "'$CMD'" 2>&1 |
    sed -n '/Broadcast completed/,$p'
