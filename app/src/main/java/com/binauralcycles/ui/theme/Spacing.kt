package com.binauralcycles.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Единая шкала отступов для экранов настроек и редактирования пресета.
 *
 * Вертикальный ритм (применять везде одинаково):
 *  - горизонтальный padding экрана ............ [lg]  16
 *  - верхний / нижний отступ экрана .......... [lg]  16
 *  - между двумя блоками                       [lg]  16
 *    (карточка / поле / график / ListItem)
 *  - между секциями (перед заголовком) ........ [xl]  24
 *  - заголовок секции padding(vertical) ....... [sm]  8
 *  - внутри карточки между группами .......... [md]  12
 *  - заголовок→описание (плотно, как блок) ...  0
 *    описание→контрол ......................... [sm]  8
 */
object Spacing {
    val xs  = 4.dp
    val sm  = 8.dp
    val md  = 12.dp
    val lg  = 16.dp
    val xl  = 24.dp
    val xxl = 32.dp
}
