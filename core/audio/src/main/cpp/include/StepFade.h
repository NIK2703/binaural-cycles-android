/**
 * Процедура затухания на скачке, ближайшем к моменту t.
 *
 *   valid = false — затухать нечего: интерполяция не STEP либо на кривой нет
 *                   ни одного настоящего скачка (все точки одинаковы);
 *                   огибающая тождественно 1;
 *   fadeSec = 0   — скачок есть, но затухание выключено (stepFadeDurationMs
 *                   = 0): ступенька звучит на полной громкости, как раньше.
 */
struct StepProcedure {
    bool  valid    = false;
    float tStarSec = 0.0f;  // мгновение скачка частоты, центр процедуры
    float fadeSec  = 0.0f;  // F — длительность затухания и нарастания
};

/**
 * Процедура, ближайшая к моменту t (ЧИСТАЯ ФУНКЦИЯ конфига).
 *
 * ВАЛИДНОСТЬ КОНСТРУКТИВНАЯ, без окрестностных зондов: в stepJumpTimes
 * лежат только узлы, где удерживаемое значение меняется, поэтому
 * «непустой список» ⇔ «где-то на кривой есть настоящий скачок». Проверять
 * знак/величину рядом с T* не нужно — и вредно (см. про -ffast-math выше).
 *
 * Окно процедуры: W = 2·F (пауза P ≡ 0). Если 2F шире зазора между
 * соседними скачками, F пропорционально сжимается — огибающая обязана
 * успеть вернуться к 1 между событиями.
 */
inline StepProcedure nearestStepProcedure(const BinauralConfig& cfg, float t) {
    StepProcedure p;
    if (cfg.curve.interpolationType != InterpolationType::STEP) return p;

    std::vector<float> scratch; // аллокация — только в патологическом пути
    const std::vector<float>& jumps = stepJumpTimesAt(cfg.curve, scratch);
    if (jumps.empty()) return p; // скачков нет — провал был бы ни на чём

    p.valid = true;
    p.tStarSec = nearestStepTimeSec(t, jumps);

    float F = static_cast<float>(cfg.stepFadeDurationMs) / 1000.0f;
    if (F <= 0.0f) return p; // выключено: голая ступенька

    // W = 2F (P ≡ 0) не шире зазора между соседними скачками.
    const float gap = stepGapSec(jumps);
    if (2.0f * F > gap) F = 0.5f * gap;

    p.fadeSec = F;
    return p;
}

/**
 * Огибающая громкости процедуры затухания на ступеньке (множитель к
 * амплитуде). Центр — в T* (мгновение скачка частоты), окно симметрично:
 *
 *   |t − T*| ≥ F                → 1.0  (процедуры нет)
 *   T* − F … T*                 → затухание 0.5·(1 + cos(π·u)), u ∈ [0,1] → 1…0
 *   T* … T* + F                 → нарастание 0.5·(1 − cos(π·u)), u ∈ [0,1] → 0…1
 *
 * Приподнятый косинус — та же кривая, что у затухания смены каналов и что у
 * FADE_OUT/FADE_IN до миграции на знаковый beat: производная на концах окна
 * равна нулю, поэтому стык с полной громкостью не слышен.
 *
 * Функция ЧЁТНАЯ относительно T*: g(T*−d) = g(T*+d). Отсюда непрерывность в
 * точке смены «ближайшего узла» — ровно посередине между соседними скачками
 * обе ветки дают одно и то же значение, разрыва нет.
 *
 * Стоимость: при интерполяции не STEP — один if, ноль аллокаций и сканов.
 */
inline float stepGainAt(const BinauralConfig& cfg, float t) {
    const StepProcedure p = nearestStepProcedure(cfg, t);
    if (!p.valid || p.fadeSec <= 0.0f) return 1.0f;

    constexpr float kPi = 3.14159265358979323846f;
    const float F = p.fadeSec;
    const float d = circularDeltaSec(t, p.tStarSec);

    if (d <= -F || d >= F) return 1.0f;        // вне окна
    if (d <= 0.0f) {                           // затухание
        const float u = (d + F) / F;           // 0 … 1
        return 0.5f * (1.0f + std::cos(kPi * u));
    }
    const float u = d / F;                     // нарастание, 0 … 1
    return 0.5f * (1.0f - std::cos(kPi * u));
}

