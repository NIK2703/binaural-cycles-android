/**
 * Список моментов скачков кривой.
 *
 * Возвращает const-ссылку на предвычисленный список (curve.stepJumpTimes) —
 * обычно именно он и возвращается. Если список ещё не построен (кривая
 * пришла в обход updateCache), он считается в scratch и возвращается ссылка
 * на scratch: вызывающий обязан потребить результат до следующего вызова с
 * тем же scratch.
 *
 * Пустой список — корректный результат («скачков нет»), а не ошибка.
 */
inline const std::vector<float>& stepJumpTimesAt(const FrequencyCurve& curve,
                                                 std::vector<float>& scratch) {
    if (curve.stepJumpTimesValid) return curve.stepJumpTimes;
    computeStepJumps(curve, scratch);
    return scratch;
}

/**
 * Ближайший к t момент скачка (сек суток ∈ [0, day)) по кругу суток.
 *
 * Поиск бинарный (список отсортирован) плюс круговое сравнение с соседом:
 * на круге ближайший к точке узел — это либо первый узел ≥ t, либо последний
 * узел < t. Никакого полного скана.
 *
 * jumps обязан быть отсортирован и лежать в [0, day) — оба свойства
 * обеспечивает computeStepJumps.
 */
inline float nearestStepTimeSec(float t, const std::vector<float>& jumps) {
    if (jumps.empty()) return 0.0f;
    constexpr float dayF = static_cast<float>(SECONDS_PER_DAY);

    float pos = std::fmod(t, dayF);
    if (pos < 0.0f) pos += dayF;

    const auto it = std::lower_bound(jumps.begin(), jumps.end(), pos);
    // Преемник в циклическом порядке (первый ≥ pos, либо первый узел суток).
    const float succ = (it == jumps.end()) ? jumps.front() : *it;
    // Предшественник (последний < pos, либо последний узел суток).
    const float pred = (it == jumps.begin()) ? jumps.back() : *(it - 1);

    const float dSucc = std::abs(circularDeltaSec(succ, pos));
    const float dPred = std::abs(circularDeltaSec(pred, pos));
    return (dSucc <= dPred) ? succ : pred;
}

/**
 * Минимальный круговой зазор между СОСЕДНИМИ скачками (сек).
 *
 * Полный аналог swapGapSec, но по списку скачков: окно процедуры не может
 * быть длиннее зазора, иначе огибающая не успевает вернуться к 1 и звук
 * замолкает навсегда. Если скачок один (или их нет) — ограничения нет,
 * возвращаем сутки.
 */
inline float stepGapSec(const std::vector<float>& jumps) {
    constexpr float dayF = static_cast<float>(SECONDS_PER_DAY);
    if (jumps.size() < 2) return dayF;

    float gap = dayF;
    for (size_t i = 0; i + 1 < jumps.size(); ++i) {
        gap = std::min(gap, jumps[i + 1] - jumps[i]);
    }
    // Смычка через полночь: последний скачок суток и первый следующего дня.
    gap = std::min(gap, dayF - (jumps.back() - jumps.front()));
    return (gap > 0.0f) ? gap : dayF;
}

