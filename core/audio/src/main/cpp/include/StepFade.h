#pragma once

// ============================================================================
// ЗАТУХАНИЕ НА СТУПЕНЬКАХ СТУПЕНЧАТОЙ ИНТЕРПОЛЯЦИИ
//
// Полный аналог процедуры смены каналов (ChannelLayout.h), применённый к
// другому событию. Обоснование, границы и разбор наложений —
// docs/design_step_interpolation_fade.md.
//
// ЧТО ЗДЕСЬ ПРОИСХОДИТ. При InterpolationType::STEP частота — СТУПЕНЬКА:
// на [t_i, t_{i+1}) звучит точка i, а в момент t_{i+1} частота мгновенно
// меняется. Слушается это как щелчок/перепад тона, и чем шире скачок (а на
// типовом циркадном графике это десятки герц), тем заметнее.
//
// ПОЧЕМУ НЕЛЬЗЯ ПРОСТО СГЛАДИТЬ ЧАСТОТУ. Ступенчатая интерполяция — это
// ОСОЗНАННЫЙ выбор пользователя: частота обязана стоять на месте и прыгать,
// она следует графику. Превращать ступеньку в глиссандо (рампа частоты между
// соседними значениями) — значит подменить выбранный тип интерполяции другим.
// Ровно по этой же причине при смене каналов отброшена рампа знака раскладки
// (см. ChannelLayout.h): плавность даёт НЕ частота, а ОГИБАЮЩАЯ ГРОМКОСТИ.
//
// ПРОЦЕДУРА (в точности как у смены каналов):
//
//     [затухание F] → [мгновение скачка T*] → [нарастание F]
//
// Приподнятый косинус на обеих половинах: на концах окна производная равна
// нулю, поэтому стык с полной громкостью не слышен, а в центре g(T*) = 0 —
// скачок частоты приходится ровно на тишину. Пауза P ≡ 0: это ровно тот
// вырожденный случай процедуры, который у смены каналов стоит по умолчанию
// (channelSwapPauseDurationMs = 0). Механизм от этого не меняется — P просто
// не вынесен в настройки.
//
// ГЛАВНОЕ СВОЙСТВО: огибающая — ЧИСТАЯ ФУНКЦИЯ (конфиг, t), как и сама
// ступенчатая кривая. Она переживает рестарт воспроизведения, смену пресета,
// смерть сервиса и скраб: нигде не хранится состояние «мы уже затухали».
// Скачок частоты при этом РЕЖЕТСЯ генератором по границе сэмпла (см.
// collectSegmentCuts), как и переворот знака раскладки.
//
// ВАЛИДНОСТЬ — КОНСТРУКТИВНАЯ: событие есть ⇔ в списке stepJumpTimes есть
// хотя бы один момент. Список содержит только те узлы, где удерживаемое
// значение ДЕЙСТВИТЕЛЬНО меняется (computeStepJumps), поэтому «ступенька без
// ступеньки» (две точки с одинаковыми частотами) провала громкости не даёт.
// Никаких соседних float, nextafter, inf и ULP-зондов: под -ffast-math на
// arm64 они схлопываются (см. docs/analysis_swap_crossfade_missing.md).
//
// ЧЁТНОСТЬ: g(T*−d) = g(T*+d). Отсюда непрерывность в точке смены
// «ближайшего узла» — ровно посередине между соседними скачками обе ветки
// дают одно и то же значение, разрыва нет даже при перекрытии окон соседей.
// ============================================================================

