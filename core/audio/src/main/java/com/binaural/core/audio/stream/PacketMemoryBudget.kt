package com.binaural.core.audio.stream

import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.update

/**
 * Единственный источник истины о том, сколько памяти можно отдать под
 * пакетные буферы, и — отсюда же — какой длины буфер доступен на каждой
 * частоте дискретизации.
 *
 * ## Откуда число 86
 *
 * Пакет — это сырые PCM_FLOAT: 2 канала × 4 байта = 8 байт на кадр. Это не
 * сжатие: меньше нельзя, не сменив формат. Значит длина буфера — это прямо
 * память, и предел длины можно выразить только через память.
 *
 * Память, которую устройство даёт приложению, — это и только это
 * `Runtime.maxMemory()` (предел РОСТА кучи; на 23049PCD8G = 256 МиБ,
 * `dalvik.vm.heapgrowthlimit`). Всё остальное измерить нельзя:
 *   - `heapsize` (512 МиБ) недоступен без `android:largeHeap`, которого в
 *     манифесте нет;
 *   - `ActivityManager.MemoryInfo.availMem` (6.2 ГиБ) — система в целом, к
 *     пределу процесса отношения не имеет;
 *   - `Runtime.freeMemory()` ВРЁТ: на ART крупные массивы живут в large
 *     object space и по `System.gc()` не возвращаются (замер — 6 циклов
 *     «выделить 32 МБ, отпустить, 2× gc» дали 34→66→98→130 МБ и ни одного
 *     возврата). Подробности — в комментарии к
 *     [BinauralStreamImpl.maybeGrowPacketBuffer].
 *
 * Доля 86% взята не «на глаз». Перебор потолка на устройстве
 * (`tools/dbgpacketlimit.sh`) показал: пакет **219 МиБ** — это 600 с при
 * 48 кГц, то есть 85.5% кучи 256 МиБ — выделяется и живёт через все пять
 * проверок (установившийся звук, шторм из 40 смен, шторм пауза→смена→resume,
 * смена частоты дискретизации, рестарт) с `oomHalvings=0` и `holders peak=1`.
 * 86% = 220 МиБ — на полмегабайта больше уже доказанного.
 *
 * Почему не 90%. 90% = 230 МиБ, а задокументированный прецедент убийства
 * процесса сторожем Xiaomi — куча 223 МиБ из 256 (`BinauralStreamImpl`,
 * причина `memory leaks occurred`). 90% лежит ВЫШЕ этой отметки, 86% — ниже.
 * Оставшиеся 14% (36 МиБ на 256 МиБ) — это всё, на чём работает само
 * приложение: zygote-классы, UI, пресеты, лог, JNI. В установившемся режиме
 * приложение занимает 5-15 МиБ, то есть запас примерно двукратный.
 *
 * ## Резерв приложению — не только процент
 *
 * Процент один ко всем устройствам не годится: те же 14% — это 18 МиБ на
 * куче 128 МиБ и 72 МиБ на куче 512 МиБ, а приложению нужно примерно
 * постоянное количество. Поэтому бюджет считается как
 * `min(86% × куча, куча − 32 МиБ)` — см. [MIN_APP_RESERVE_BYTES]. На куче
 * 256 МиБ и выше это ничего не меняет (бюджет тот же 220 МиБ, проверенная
 * замером стопа 10 мин @48 кГц остаётся), меняется только низший сегмент.
 * Связь потолка с кучей от этого не ослабла, а стала корректнее: нижняя
 * граница резерва теперь не зависит от того, сколько кучи дало устройство.
 *
 * ## Что отсюда следует для длины буфера
 *
 * `maxSeconds = потолок / (частота × 8)`. Одна и та же память — это РАЗНАЯ
 * длительность на разных частотах, поэтому слайдер и обязан иметь свой
 * диапазон на каждую частоту: 10 минут при 48 кГц и 60 минут при 8 кГц
 * стоят одинаково. На 23049PCD8G (куча 256 МиБ, потолок 220 МиБ):
 *
 * | SR, Гц | макс. секунд | стопы слайдера, мин |
 * |--------|--------------|---------------------|
 * |   8000 |         3600 | 1, 2, 5, 10, 15, 20, 30, 40, 50, 60 |
 * |  16000 |         1800 | 1, 2, 5, 10, 15, 20, 30 |
 * |  22050 |         1200 | 1, 2, 5, 10, 15, 20 |
 * |  44100 |          600 | 1, 2, 5, 10 |
 * |  48000 |          600 | 1, 2, 5, 10 |
 *
 * Длина каждой стопы вычисляется один раз в таблице [REQUIRED_BYTES]; в рантайме
 * движок лишь сравнивает готовые байты с потолком (см. [requiredBytesFor]).
 * Таблица ниже приведена для кучи ≥ 228.6 МиБ, где правит процент; на меньшей
 * куче правит пол резерва, и стопы сдвигаются вниз.
 *
 * То есть час буфера доступен только на 8 кГц — и это честно: на 48 кГц час
 * стоил бы 1.38 ГБ, которых нет ни у одного телефона.
 *
 * ## Что здесь НЕ решается
 *
 * Здесь определяется только ПРЕДЕЛ — сколько памяти можно отдать и какая
 * длина в него влезает. Выбор конкретной длины внутри предела за движком
 * (`STARTUP_PACKET_SECONDS` и доращивание писателя), и он от памяти не
 * зависит: длина пакета почти не влияет ни на CPU, ни на число пробуждений
 * (подробности в `docs/hotpath_battery_memory_audit_2026-08-31.md`).
 */
object PacketMemoryBudget {

    /** Доля кучи, отданная под пакетные буферы, проценты. */
    const val DEFAULT_HEAP_PERCENT = 86

    /** Границы ручной подмены (debug-команда `packetpct`). */
    const val MIN_HEAP_PERCENT = 10
    const val MAX_HEAP_PERCENT = 95

    /** Байт на кадр: 2 канала × float32. Смена формата меняет ВСЕ расчёты. */
    const val BYTES_PER_FRAME = 8L

    /**
     * Абсолютный предохранитель: 86% от кучи в 4 ГиБ — это 3.4 ГиБ на пакет,
     * и такой процент перестаёт быть осмысленным. Реальная защита от
     * невменяемых чисел, а не рабочий предел: на телефоне он не срабатывает
     * (86% от 256 МиБ = 220 МиБ, что ниже 512 МиБ).
     */
    val ABSOLUTE_MAX_BYTES: Long = 512L * 1024 * 1024

    /** Нижняя граница: меньше пакет теряет смысл (не покрывает и буфера трека). */
    val ABSOLUTE_MIN_BYTES: Long = 4L * 1024 * 1024

    /**
     * Абсолютный минимум, который обязан остаться САМОМУ приложению, байт.
     *
     * Процент ([DEFAULT_HEAP_PERCENT]) масштабирует резерв вместе с кучей:
     * 14% — это 18 МиБ на куче 128 МиБ и 72 МиБ на куче 512 МиБ, тогда как
     * приложению нужно примерно постоянное количество (замер: 5-15 МиБ в
     * установившемся режиме). Чистый процент даёт минимальный запас ровно на
     * тех устройствах, где LMK всего агрессивнее. Пол делает запас
     * независимым от кучи снизу:
     *
     *     бюджет = min(процент × куча, куча − MIN_APP_RESERVE_BYTES)
     *
     * Точка переключения — куча 228.6 МиБ (0.14 × H = 32 МиБ). Ниже правит
     * пол, выше — процент. Отсюда следствие, ради которого пол и вводился:
     * на куче 256 МиБ (POCO 23049PCD8G) и выше значение НЕ меняется вовсе —
     * бюджет по-прежнему 220 МиБ, и проверенная замером стопа 10 мин @48 кГц
     * остаётся доступной. Меняется только низший сегмент: на куче 128 МиБ
     * бюджет 110 → 96 МиБ, и на 48 кГц доступна стопа 2 мин вместо 5. Это
     * осознанная плата за гарантированный запас там, где он нужнее.
     */
    val MIN_APP_RESERVE_BYTES: Long = 32L * 1024 * 1024

    /**
     * Потолок ОДНОГО пакета по ABI: 256 МиБ на 64-бит, 96 МиБ на 32-бит.
     *
     * Живёт здесь, а не в движке, потому что это потолок ПАКЕТА и слайдер
     * обязан его видеть. Пока он лежал в `BinauralStreamImpl.maxBufferBytes`
     * и применялся только в prepare(), на устройствах с кучей ≥ 341 МиБ
     * слайдер предлагал стопы, которые движок молча урезал: 40 мин @16 кГц
     * давали 35 мин, 15 мин @48 кГц — 11.6 мин. На куче 256 МиБ потолок не
     * связывает ни на одной частоте (оттого на POCO и не был замечен).
     *
     * Число не про объём памяти в устройстве, а про RSS процесса: 256 МиБ
     * не-movable массива — это порядок, на котором фоновый LMK начинает
     * присматриваться. На 32-bit ABI предел ниже из-за узкого виртуального
     * адресного пространства: смежные 1+ ГиБ там не выделить.
     */
    val ABI_CAP_BYTES: Long =
        if (android.os.Build.SUPPORTED_64_BIT_ABIS.isNotEmpty()) 256L * 1024 * 1024
        else 96L * 1024 * 1024

    /**
     * Структурный предел длительности пакета. Не память, а здравый смысл:
     * пакет длиннее часа — это час, в течение которого правка графика
     * пользователем дойдёт до звука только на следующей генерации.
     */
    const val MAX_SECONDS = 3600

    /** Минимальная длительность пакета — покрыть хотя бы буфер трека. */
    const val MIN_SECONDS = 1

    /** Частоты дискретизации, которые знает приложение. */
    private val RATES = intArrayOf(8000, 16000, 22050, 44100, 48000)

    /**
     * Лестница значений слайдера в минутах: мелкие шаги в начале (там каждый
     * шаг меняет число пробуждений в час кратно), а ПОСЛЕ 20 минут — ровно по
     * 10 минут до часа.
     *
     * Отсекается по памяти в [sliderStopsMinutes]: на 48 кГц доступны только
     * первые четыре стопы, на 8 кГц — вся лестница целиком. Круглые значения
     * берутся ВНИЗ, иначе выбранная длина молча урезалась бы движком, и
     * слайдер врал бы так же, как врал дефолт 600 с при потолке пакета 32 МБ.
     */
    private val MINUTE_LADDER = listOf(1, 2, 5, 10, 15, 20, 30, 40, 50, 60)

    /** Индекс стоп-минуты в [MINUTE_LADDER] — для обращения к таблице байт. */
    private val LADDER_INDEX: Map<Int, Int> = MINUTE_LADDER.withIndex().associate { (i, m) -> m to i }

    /**
     * ПРЕДРАССЧИТАННАЯ таблица требуемой памяти: байт на пару (частота,
     * стоп-минута). Значения ВЫЧИСЛЕНЫ ЗАРАНЕЕ и записаны литералами — в
     * приложении никакого умножения `частота × 8 × секунды` НЕ ПРОИСХОДИТ,
     * ни на лету, ни при загрузке класса. При смене настроек пользователем
     * движок лишь СРАВНИВАЕТ готовое число с текущим запасом памяти
     * приложения ([budgetBytes]). Это прямое требование: расчёт длины не
     * должен идти на лету, только сравнение с резервом.
     *
     * Порядок в каждом `longArrayOf` — как в [MINUTE_LADDER]
     * (1,2,5,10,15,20,30,40,50,60 мин). Пересчёт при смене формата (другой
     * [BYTES_PER_FRAME]) — вручную, здесь.
     */
    private val REQUIRED_BYTES: Map<Int, LongArray> = mapOf(
        8000 to longArrayOf(
            3_840_000, 7_680_000, 19_200_000, 38_400_000, 57_600_000,
            76_800_000, 115_200_000, 153_600_000, 192_000_000, 230_400_000,
        ),
        16000 to longArrayOf(
            7_680_000, 15_360_000, 38_400_000, 76_800_000, 115_200_000,
            153_600_000, 230_400_000, 307_200_000, 384_000_000, 460_800_000,
        ),
        22050 to longArrayOf(
            10_584_000, 21_168_000, 52_920_000, 105_840_000, 158_760_000,
            211_680_000, 317_520_000, 423_360_000, 529_200_000, 635_040_000,
        ),
        44100 to longArrayOf(
            21_168_000, 42_336_000, 105_840_000, 211_680_000, 317_520_000,
            423_360_000, 635_040_000, 846_720_000, 1_058_400_000, 1_270_080_000,
        ),
        48000 to longArrayOf(
            23_040_000, 46_080_000, 115_200_000, 230_400_000, 345_600_000,
            460_800_000, 691_200_000, 921_600_000, 1_152_000_000, 1_382_400_000,
        ),
    )

    /**
     * Предрассчитанный объём памяти под пакет заданной длины на заданной
     * частоте, байт. БЕЗ вычислений на лету — значение берётся из готовой
     * таблицы [REQUIRED_BYTES].
     *
     * `minutes` обязано быть значением из [MINUTE_LADDER] (именно их и
     * сравнивают со стопами). Для значения вне лестницы — защитный путь
     * (не должен срабатывать): вернуть «бесконечность», чтобы такая стопа
     * никогда не прошла фильтр памяти, то есть не привела к OOM.
     */
    @JvmStatic
    fun requiredBytesFor(rateHz: Int, minutes: Int): Long {
        val arr = REQUIRED_BYTES[rateHz] ?: return Long.MAX_VALUE
        val i = LADDER_INDEX[minutes] ?: return Long.MAX_VALUE
        return arr[i]
    }

    @Volatile
    private var percentOverride = 0

    /** Подменить долю кучи на ходу; 0 — вернуться к [DEFAULT_HEAP_PERCENT]. */
    @JvmStatic
    fun setHeapPercent(percent: Int) {
        percentOverride = if (percent <= 0) 0 else percent.coerceIn(MIN_HEAP_PERCENT, MAX_HEAP_PERCENT)
        bumpCeilingRevision()
    }

    /** Действующая доля кучи в процентах: override или константа. */
    @JvmStatic
    fun heapPercentEffective(): Int {
        val p = percentOverride
        return if (p > 0) p else DEFAULT_HEAP_PERCENT
    }

    /** Предел роста кучи — единственная измеримая величина. См. шапку файла. */
    @JvmStatic
    fun heapBytes(): Long = Runtime.getRuntime().maxMemory()

    /**
     * Сколько байт отдано под пакетные буферы (на один поток — см. инвариант).
     *
     * Два предела, берётся меньший: доля кучи и остаток после обязательного
     * резерва приложению. См. [MIN_APP_RESERVE_BYTES].
     */
    @JvmStatic
    fun budgetBytes(): Long {
        val raw = heapBytes() * heapPercentEffective() / 100L
        return applyReserve(raw)
    }

    /**
     * Учесть обязательный резерв приложению: сколько бы ни просил процент,
     * самому приложению остаётся не меньше [MIN_APP_RESERVE_BYTES].
     *
     * Когда куча МЕНЬШЕ резерва, `coerceIn` поднимает результат до
     * [ABSOLUTE_MIN_BYTES] — на такой куче пакет не помещается вовсе, и лучше
     * отдать приложению всё, чем уронить его аллокацией заведомо
     * невменяемого буфера.
     */
    private fun applyReserve(raw: Long): Long {
        val byReserve = heapBytes() - MIN_APP_RESERVE_BYTES
        return minOf(raw, byReserve).coerceIn(ABSOLUTE_MIN_BYTES, ABSOLUTE_MAX_BYTES)
    }

    /** Сколько байт кучи остаётся самому приложению. */
    @JvmStatic
    fun appReserveBytes(): Long = (heapBytes() - budgetBytes()).coerceAtLeast(0L)

    // ---------------- Потолок, который реально применит движок ----------------

    /**
     * Потолок пакета, подменяемый НА ХОДУ (debug-команда `packetmax`).
     * 0 — без ручного потолка.
     *
     * Нужен, чтобы искать предел аллокации на устройстве за одну установку:
     * без него каждый шаг перебора требовал бы пересборки и установки.
     *
     * Живёт здесь по той же причине, что и [ABI_CAP_BYTES]: это часть ответа
     * на вопрос «сколько можно», и слайдер обязан его видеть — иначе
     * `packetmax 64` молча урезал бы выбранную пользователем стопу.
     */
    @Volatile
    private var packetMaxBytesOverride = 0L

    /**
     * Задать ручной потолок пакета в байтах; 0 — снять.
     * Значение клампится в [ABSOLUTE_MIN_BYTES]..[ABI_CAP_BYTES].
     */
    @JvmStatic
    fun setPacketMaxBytes(bytes: Long) {
        packetMaxBytesOverride = if (bytes <= 0L) 0L
        else bytes.coerceIn(ABSOLUTE_MIN_BYTES, ABI_CAP_BYTES)
        bumpCeilingRevision()
    }

    /** Действующий ручной потолок: override или «потолка нет». */
    @JvmStatic
    fun packetMaxBytesEffective(): Long {
        val o = packetMaxBytesOverride
        return if (o > 0L) o else Long.MAX_VALUE
    }

    /**
     * Потолок, выученный по факту: сколько байт аллокация реально смогла
     * взять. Стартовое значение — «не ограничен», уменьшается ТОЛЬКО вниз.
     *
     * Зачем. `maxMemory()` — это предел РОСТА кучи, а не гарантия: под
     * системным давлением ART вправе не дотянуть до него (без
     * `android:largeHeap` доступна лишь `heapgrowthlimit` — 256 МБ на
     * 23049PCD8G против 512 МБ `heapsize`). Тогда allocateDirect ловит
     * OutOfMemoryError и уполовинивает запрос, поднимая сборку. Один провал
     * не страшен, но повтор на каждом потоке — это и есть GC-трэш, от
     * которого сторож убивал процесс. Запомнить достигнутый потолок и не
     * просить больше — дешевле, чем платить сборкой каждый раз.
     *
     * Отпускается, но НЕ всегда — см. [releaseAdaptiveCeilingIfSafe].
     */
    private val adaptiveCeiling = java.util.concurrent.atomic.AtomicLong(Long.MAX_VALUE)

    /**
     * true — [adaptiveCeiling] хотя бы раз опускался в провале, который
     * объясняется КОНКУРЕНЦИЕЙ, а не абсолютным пределом устройства.
     *
     * Именно это различие решает, можно ли храповик отпустить. См.
     * [noteAllocationFailure].
     */
    @Volatile
    private var ceilingLoweredUnderContention = false

    /** Выученный потолок, байт; [Long.MAX_VALUE] — не ограничен. */
    @JvmStatic
    fun adaptiveCeilingBytes(): Long = adaptiveCeiling.get()

    /**
     * Запомнить провал аллокации: `sizeBytes` не дали, при этом другие потоки
     * держали `otherHeldBytes` пакетной памяти.
     *
     * Признак конкуренции — НЕ «сколько потоков держало пакет», а арифметика:
     * если `otherHeldBytes + sizeBytes` не влезает в общий бюджет, провал
     * объясняется тем, что память была занята, а не тем, что устройство не
     * даёт столько вообще. Освободится — запрос может и пройти.
     *
     * Почему не считать по числу держателей. Самый жизненный случай — хэндофф:
     * старый поток держит дорощенный пакет, новый просит такой же и падает.
     * Новый ещё ничего не закоммитил, поэтому держатель на момент провала
     * ровно ОДИН (старый), а провал — чистая конкуренция. Проверка «держателей
     * больше одного» этот случай не ловит вовсе. Арифметика ловит: 219 + 219
     * MiB при бюджете 220 MiB не влезает никак.
     *
     * Обратная сторона у признака честная: при `otherHeldBytes == 0` (провал
     * на стартовом пакете первого потока или при доращивании одиночки) храповик
     * НЕ отпускается — это предел устройства, и пробовать снова бессмысленно:
     * на тесном устройстве получим OOM на каждый play.
     */
    @JvmStatic
    fun noteAllocationFailure(sizeBytes: Long, otherHeldBytes: Long) {
        if (otherHeldBytes > 0L && sizeBytes + otherHeldBytes > globalBudgetBytes()) {
            ceilingLoweredUnderContention = true
        }
        adaptiveCeiling.getAndUpdate { c -> minOf(c, sizeBytes / 2L) }
        bumpCeilingRevision()
    }

    /**
     * Отпустить храповик, когда пакетных буферов не осталось вовсе.
     *
     * Вызывается из `commitPacketBudget(0)` последнего живого потока, то есть
     * в момент, когда под пакеты не занято НИЧЕГО и пробовать предел заново
     * безопасно. Но только если прошлое опускание объяснялось конкуренцией
     * ([noteAllocationFailure]): иначе вместо одного провала за сессию
     * получим провал на каждый play.
     *
     * Флаг снимается ДО сброса потолка, значит повторная попытка ровно одна:
     * если перепроверка тоже провалилась, она провалилась на пустой памяти —
     * это предел устройства, и храповик встаёт уже навсегда до `pcreset`.
     */
    @JvmStatic
    fun releaseAdaptiveCeilingIfSafe() {
        if (!ceilingLoweredUnderContention) return
        ceilingLoweredUnderContention = false
        adaptiveCeiling.set(Long.MAX_VALUE)
        bumpCeilingRevision()
    }

    /** Сбросить выученный потолок безусловно (debug-команда `pcreset`). */
    @JvmStatic
    fun resetAdaptiveCeiling() {
        ceilingLoweredUnderContention = false
        adaptiveCeiling.set(Long.MAX_VALUE)
        bumpCeilingRevision()
    }

    // ---------------- Ревизия потолка: как UI узнаёт, что потолок сменился ----------------

    /**
     * Счётчик изменений всего, от чего зависит [engineCeilingBytes].
     *
     * Зачем отдельный счётчик, если стопы слайдера — это десять сравнений из
     * готовой таблицы. Затем, что [sliderStopsMinutes] читает ИЗМЕНЯЕМОЕ
     * состояние (ручной `packetmax`, выученный после OOM потолок), а UI
     * кэшировал результат `remember`-ом по одной частоте дискретизации — то
     * есть на весь процесс. Слайдер показывал стопы, которых уже нет: потолок
     * сузился, а список остался прежним, и выбранная стопа снова молча
     * урезалась движком. Ревизия даёт Compose честный ключ: список
     * пересчитывается ровно тогда, когда изменился потолок, и сохраняет
     * устойчивый identity между рекомпозициями (а не пересоздаётся каждый
     * кадр ради десяти сравнений).
     *
     * Растёт во всех сеттерах, меняющих потолок; НЕ растёт на
     * [setGlobalHeapPercent] — общий бюджет на один пакет не влияет.
     */
    private val ceilingRevision = MutableStateFlow(0L)

    /**
     * Поток ревизии потолка для UI. Подписка — `collectAsState()`; начальное
     * значение приходит сразу, отдельного чтения не нужно.
     */
    @JvmStatic
    fun ceilingRevisionFlow(): StateFlow<Long> = ceilingRevision

    private fun bumpCeilingRevision() {
        ceilingRevision.update { it + 1 }
    }

    /**
     * Сколько байт движок реально даст под ОДИН пакет.
     *
     * Это ЕДИНСТВЕННАЯ функция, по которой обязаны считать и слайдер
     * ([sliderStopsMinutes], [maxSecondsFor]), и prepare(). Всё, что урезает
     * пакет, собрано здесь ровно один раз:
     *
     *   1. [budgetBytes] — процент кучи минус резерв приложению;
     *   2. [packetMaxBytesEffective] — ручной потолок debug-команды;
     *   3. [adaptiveCeiling] — выученный по факту OOM;
     *   4. [ABI_CAP_BYTES] — абсолютный предел по ABI.
     *
     * Порядок важен в одном месте: [ABSOLUTE_MIN_BYTES] — нижняя граница
     * ДО выученного потолка, а не после. Если устройство не даёт даже 4 МиБ,
     * так тому и быть: allocateDirect урежет и prepare() подстроит длину
     * пакета по факту ёмкости.
     *
     * Раньше первые два предела знал только движок, а слайдер считал по
     * бюджету кучи — отсюда и тихое усечение, которое комментарий в UI
     * обещал невозможным.
     */
    @JvmStatic
    fun engineCeilingBytes(): Long =
        budgetBytes()
            .coerceIn(ABSOLUTE_MIN_BYTES, packetMaxBytesEffective())
            .coerceAtMost(adaptiveCeiling.get())
            .coerceAtMost(ABI_CAP_BYTES)

    // ---------------- Общий бюджет (сумма по всем живым потокам) ----------------

    @Volatile
    private var globalPercentOverride = 0

    /**
     * Подменить долю кучи под СУММУ пакетов всех потоков (debug-команда
     * `packetgpct`); 0 — как [heapPercentEffective].
     *
     * Зачем отдельная ручка, если инвариант «один поток» делает сумму равной
     * одному пакету. Чтобы проверять инвариант, а не предполагать его: с
     * `packetgpct 43` бюджет равен половине обычного, и любое нарушение
     * («два потока держат полный пакет») ловится отказом дорастить, а не
     * посмертным разбором лога.
     */
    @JvmStatic
    fun setGlobalHeapPercent(percent: Int) {
        globalPercentOverride =
            if (percent <= 0) 0 else percent.coerceIn(MIN_HEAP_PERCENT, MAX_HEAP_PERCENT)
    }

    /** Действующая доля кучи под сумму пакетов, проценты. */
    @JvmStatic
    fun globalHeapPercentEffective(): Int {
        val p = globalPercentOverride
        return if (p > 0) p else heapPercentEffective()
    }

    /**
     * Предел суммы пакетов всех живых потоков, байт.
     *
     * При инварианте одного потока совпадает с [budgetBytes] — и это нормально,
     * а не дублирование: бюджет проверяет СУММУ, а инвариант гарантирует, что
     * в сумме одно слагаемое. Разница проявится ровно в тот момент, когда
     * инвариант сломается.
     */
    @JvmStatic
    fun globalBudgetBytes(): Long {
        val raw = heapBytes() * globalHeapPercentEffective() / 100L
        return applyReserve(raw)
    }

    /**
     * Максимальная длительность пакета на этой частоте, секунды.
     *
     * Память одна и та же на всех частотах, поэтому на низкой частоте тот же
     * бюджет покупает proportionally больше секунд — именно отсюда разные
     * диапазоны слайдера.
     *
     * Считаем по [engineCeilingBytes], а не по [budgetBytes]: потолок движка
     * включает всё, что реально урежет пакет (ABI, выученный после OOM,
     * ручной `packetmax`), и слайдеру нужен именно он. Иначе стопа, которая
     * влезла в бюджет кучи, молча урезалась бы движком — ровно та ложь,
     * которую этот класс и был призван устранить.
     */
    @JvmStatic
    fun maxSecondsFor(rateHz: Int): Int {
        if (rateHz <= 0) return MIN_SECONDS
        val ceiling = engineCeilingBytes()
        val arr = REQUIRED_BYTES[rateHz] ?: return MIN_SECONDS
        // Последняя стопа, влезающая в потолок — именно её секунды и берём.
        var bestMinutes = MINUTE_LADDER.first()
        for (i in MINUTE_LADDER.indices) {
            if (arr[i] <= ceiling) bestMinutes = MINUTE_LADDER[i]
        }
        return (bestMinutes * 60L).coerceIn(MIN_SECONDS.toLong(), MAX_SECONDS.toLong()).toInt()
    }

    /** То же в миллисекундах — для клампа интервала генерации в менеджере. */
    @JvmStatic
    fun maxIntervalMsFor(rateHz: Int): Int = maxSecondsFor(rateHz) * 1000

    /**
     * Стопы слайдера для этой частоты, минуты. Свой набор на каждый SR.
     *
     * Берём лестницу целиком и отсекаем всё, что не влезает в [engineCeilingBytes]:
     * круглое значение всегда берётся ВНИЗ, иначе выбранная длина молча
     * урезалась бы движком, и слайдер врал бы так же, как врал дефолт
     * 600 с при потолке пакета 32 МиБ.
     *
     * NB: список ЗАВИСИТ от состояния, которое меняется на ходу — выученного
     * потолка и ручного `packetmax`. Поэтому Compose обязан пересчитывать
     * стопы, а не кэшировать их на весь процесс; ключ `remember` по одной
     * частоте дискретизации больше недостаточен.
     */
    @JvmStatic
    fun sliderStopsMinutes(rateHz: Int): List<Int> {
        val ceiling = engineCeilingBytes()
        val arr = REQUIRED_BYTES[rateHz] ?: return listOf(MINUTE_LADDER.first())
        // Сравниваем ГОТОВЫЕ байты из таблицы с потолком — без умножений на лету.
        val stops = MINUTE_LADDER.filterIndexed { i, _ -> arr[i] <= ceiling }
        // Лестница обязана иметь хотя бы две стопы, иначе слайдер не слайдер.
        // На куче, где не влезает и две минуты, даём минимум из лестницы.
        return if (stops.size >= 2) stops else listOf(MINUTE_LADDER.first())
    }

    /**
     * Втянуть сохранённое значение в диапазон этой частоты, округлением ВНИЗ.
     *
     * Нужно на два случая: значение из хранилища старой версии и смена
     * частоты дискретизации, после которой прежние 30 минут могут перестать
     * влезать. Вниз, а не вверх: вверх — это риск OOM, вниз — только чуть
     * чаще генерация.
     */
    @JvmStatic
    fun coerceMinutes(rateHz: Int, minutes: Int): Int {
        val stops = sliderStopsMinutes(rateHz)
        return stops.lastOrNull { it <= minutes } ?: stops.first()
    }

    private fun manualCapText(): String {
        val o = packetMaxBytesOverride
        return if (o > 0L) "${o / (1024 * 1024)}МБ" else "нет"
    }

    private fun adaptiveCeilingText(): String {
        val c = adaptiveCeiling.get()
        return if (c == Long.MAX_VALUE) "нет" else "${c / (1024 * 1024)}МБ"
    }

    /** Сводка для диагностики: бюджет, диапазоны и предрассчитанная память на стоп. */
    @JvmStatic
    fun report(): String {
        val mb = 1024L * 1024L
        return buildString {
            append("heap=${heapBytes() / mb}МБ доля=${heapPercentEffective()}% " +
                "бюджет=${budgetBytes() / mb}МБ резервПриложению=${appReserveBytes() / mb}МБ\n")
            append("потолокДвижка=${engineCeilingBytes() / mb}МБ " +
                "(abi=${ABI_CAP_BYTES / mb}МБ ручной=${manualCapText()} " +
                "выученный=${adaptiveCeilingText()})\n")
            append("диапазоны: ")
            append(RATES.joinToString(", ") { r ->
                "${r}Гц=${maxSecondsFor(r)}с [${sliderStopsMinutes(r).joinToString("/")}мин]"
            })
            append("\nпамятьНаСтоп(МБ): ")
            append(RATES.joinToString("  ") { r ->
                val stops = sliderStopsMinutes(r)
                "${r}Гц=" + stops.joinToString(",") { m -> "$m→${requiredBytesFor(r, m) / mb}" }
            })
        }
    }
}
